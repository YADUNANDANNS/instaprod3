"""
Pure-Python gradient-boosted-tree predictor.

Replaces the joblib-pickled XGBoost classifiers used in the F1Y build. The
trained trees are stored as plain Python data in model_real.py and
model_demo.py (generated by tools/export_models.py), and this module walks
them. It needs nothing beyond the Python standard library: no xgboost, no
scikit-learn, no joblib, no numpy.

Why it reproduces XGBoost exactly:
- XGBoost casts every feature value to float32 before comparing it with a
  split threshold, and it sends a row LEFT when value < threshold. Both are
  done here (thresholds are stored as exact float32 values).
- XGBoost sums leaf values per class in float32, starting from the model's
  per-class base margin. The same order and rounding are used here.
- multi:softmax picks the class with the largest margin; class probabilities
  are the softmax of the margins. Both are done here.

Tree format (see the generated model files): a node is either a bare float
(a leaf value) or a 4-tuple (feature_index, threshold, left, right).

Inputs are never missing in this app (every field has a default), so the
missing-value branch of XGBoost is not needed and is not implemented.
"""

import math
from struct import Struct

_F32 = Struct("<f")


def to_float32(x: float) -> float:
    """Round a Python float to the nearest float32 value (returned as a float)."""
    try:
        return _F32.unpack(_F32.pack(x))[0]
    except OverflowError:
        return math.inf if x > 0 else -math.inf


class SimpleLabelEncoder:
    """Minimal stand-in for sklearn's LabelEncoder (classes_ + inverse_transform)."""

    def __init__(self, classes):
        self.classes_ = list(classes)

    def inverse_transform(self, indices):
        return [self.classes_[int(i)] for i in indices]


class TreeEnsembleClassifier:
    """Multiclass softmax classifier over per-class lists of trees."""

    def __init__(self, trees_by_class, base_margin, feature_columns, classes):
        self._trees = trees_by_class
        self._base = tuple(to_float32(b) for b in base_margin)
        self.feature_columns = list(feature_columns)
        self.classes_ = list(classes)
        self.n_classes_ = len(self.classes_)
        if len(self._trees) != self.n_classes_ or len(self._base) != self.n_classes_:
            raise ValueError("Model data is inconsistent: class count mismatch.")

    def margins(self, features):
        """Raw per-class scores for one row (a sequence in feature_columns order)."""
        if len(features) != len(self.feature_columns):
            raise ValueError(
                f"Expected {len(self.feature_columns)} features, got {len(features)}."
            )
        x = [to_float32(float(v)) for v in features]
        out = []
        for class_trees, base in zip(self._trees, self._base):
            margin = base
            for node in class_trees:
                while node.__class__ is tuple:
                    feature, threshold, left, right = node
                    node = left if x[feature] < threshold else right
                margin = to_float32(margin + node)
            out.append(margin)
        return out

    def predict_proba(self, features):
        margins = self.margins(features)
        top = max(margins)
        exps = [math.exp(m - top) for m in margins]
        total = sum(exps)
        return [e / total for e in exps]

    def predict(self, features):
        """Index of the winning class (first one wins a tie, like numpy.argmax)."""
        margins = self.margins(features)
        return margins.index(max(margins))
